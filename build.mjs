// Builds index.html (English), it/index.html and es/index.html from src/content.mjs, plus map.css.
// Run: node build.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { T, LANGS, TECH, PROJECTS, LINKS, STACKS, EMAIL, GITHUB, LINKEDIN, TESEO_OCR, SITE, GOOGLE_VERIFICATION } from './src/content.mjs';

const TODAY = new Date().toISOString().slice(0, 10);

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// ---------- the map ----------
// Projects are the heavy nodes (name and one fact); technologies are light labels. Below 60rem the map becomes a list.
const W = 720, H = 660, PX = 24, PW = 268, PH = 88, TX = 512, TW = 184, TH = 32;
const ty = (i) => 64 + i * 55;

function map(t) {
  const edges = [];
  for (const p of PROJECTS) for (const name of p.stack) {
    const y2 = ty(TECH.indexOf(name)), x1 = PX + PW, x2 = TX, mid = (x1 + x2) / 2;
    edges.push(`<path class="e p-${p.id} t-${slug(name)}" d="M${x1} ${p.y} C${mid} ${p.y} ${mid} ${y2} ${x2} ${y2}"/>`);
  }
  const projects = PROJECTS.map((p) => {
    const f = t.mapFacts[p.id];
    return `
    <a class="node node--p node--${p.id}" href="#${p.id}" aria-label="${esc(p.name)}: ${esc(f)}">
      <rect x="${PX + 0.5}" y="${p.y - PH / 2}" width="${PW - 1}" height="${PH}" rx="10"/>
      <text class="node__name" x="${PX + 22}" y="${p.y - 6}">${esc(p.name)}</text>
      <text class="node__fact${p.id === 'teseo' ? ' node__fact--measured' : ''}" x="${PX + 22}" y="${p.y + 24}">${esc(f)}</text>
    </a>`;
  }).join('');
  const tech = TECH.map((name, i) => `
    <g class="node node--t node--${slug(name)}" tabindex="0" role="img" aria-label="${esc(name)}">
      <rect x="${TX + 0.5}" y="${ty(i) - TH / 2}" width="${TW - 1}" height="${TH}" rx="6"/>
      <text x="${TX + 14}" y="${ty(i) + 5}">${esc(name)}</text>
    </g>`).join('');
  return `<svg class="map" viewBox="0 0 ${W} ${H}" role="group" aria-label="${esc(t.mapLabel)}">
    <g class="map__head" aria-hidden="true"><text x="${PX}" y="22">${esc(t.mapHead[0])}</text><text x="${TX}" y="22">${esc(t.mapHead[1])}</text></g>
    <g class="edges" aria-hidden="true">${edges.join('')}</g>${projects}${tech}
  </svg>`;
}

function mapList(t) {
  return `<ol class="map-list">${PROJECTS.map((p) => `
    <li><a href="#${p.id}">${esc(p.name)}</a><span class="map-list__fact${p.id === 'teseo' ? ' is-measured' : ''}">${esc(t.mapFacts[p.id])}</span><span class="map-list__stack">${p.stack.map(esc).join(', ')}</span></li>`).join('')}
  </ol>`;
}

function mapCss() {
  const r = [];
  for (const p of PROJECTS) {
    const on = `.map:has(.node--${p.id}:is(:hover, :focus-visible))`;
    r.push(`${on} .e { opacity: 0.18; }`, `${on} .e.p-${p.id} { opacity: 1; stroke: var(--color-cool); }`);
    r.push(`${on} :is(${p.stack.map((s) => `.node--${slug(s)}`).join(', ')}) rect { stroke: var(--color-cool); fill: var(--color-cool-soft); }`);
  }
  for (const name of TECH) {
    const s = slug(name), on = `.map:has(.node--${s}:is(:hover, :focus-visible))`;
    const users = PROJECTS.filter((p) => p.stack.includes(name));
    r.push(`${on} .e { opacity: 0.18; }`, `${on} .e.t-${s} { opacity: 1; stroke: var(--color-cool); }`);
    r.push(`${on} :is(${users.map((p) => `.node--${p.id}`).join(', ')}) rect { stroke: var(--color-cool); }`);
  }
  return `/* generated by build.mjs: map highlights, no JavaScript needed */\n${r.join('\n')}\n`;
}

// ---------- structured data ----------
function jsonLd(code) {
  const t = T[code], url = SITE + LANGS.find((l) => l.code === code).dir;
  const data = {
    '@context': 'https://schema.org',
    '@type': 'ProfilePage',
    url,
    inLanguage: code,
    name: t.title,
    description: t.description,
    dateModified: TODAY,
    mainEntity: {
      '@type': 'Person',
      '@id': SITE + '#francesco',
      name: 'Francesco Carlucci',
      url: SITE,
      image: SITE + 'images/og-en.png',
      jobTitle: 'Software Engineer',
      worksFor: { '@type': 'Organization', name: 'MemorAIz' },
      alumniOf: [
        { '@type': 'CollegeOrUniversity', name: 'Alma Mater Studiorum, Università di Bologna' },
        { '@type': 'CollegeOrUniversity', name: 'Universitat Politècnica de València' },
      ],
      address: { '@type': 'PostalAddress', addressLocality: 'Bologna', addressCountry: 'IT' },
      email: 'mailto:' + EMAIL,
      sameAs: [GITHUB, LINKEDIN],
      knowsLanguage: ['it', 'en', 'es'],
      knowsAbout: ['TypeScript', 'React', 'Next.js', 'PostgreSQL', 'AWS', 'Large language models', 'Full-stack web development'],
    },
  };
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

// ---------- the page ----------
